import { execFileSync } from 'node:child_process';
import { readFileSync,writeFileSync,mkdirSync } from 'node:fs';
mkdirSync('node_modules/.cache/crowd',{recursive:true});
const output='node_modules/.cache/crowd/transfer.wasm';
execFileSync(process.execPath,['node_modules/assemblyscript/bin/asc.js','native/crowd-transfer.ts','-O3','--noAssert','--runtime','stub','--importMemory','--outFile',output],{stdio:'inherit'});
const source=`// Generated by npm run build:transfer; edit native/crowd-transfer.ts instead.\nexport const CROWD_TRANSFER_BASE64 = '${readFileSync(output).toString('base64')}';\n`;
if(process.argv.includes('--check')) {
  if(readFileSync('src/core/crowd-transfer.generated.ts','utf8').replace(/\r\n/g,'\n')!==source)throw new Error('Stale crowd transfer kernel: run npm run build:transfer.');
} else writeFileSync('src/core/crowd-transfer.generated.ts',source);
