import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
mkdirSync('node_modules/.cache/crowd',{recursive:true});
const output='node_modules/.cache/crowd/contact.wasm';
execFileSync(process.execPath,['node_modules/assemblyscript/bin/asc.js','native/contact-kernel.ts','-O3','--noAssert','--runtime','stub','--importMemory','--outFile',output],{stdio:'inherit'});
const encoded=readFileSync(output).toString('base64');
const source=`// Generated by npm run build:contact; edit native/contact-kernel.ts instead.\nexport const CONTACT_KERNEL_BASE64 = '${encoded}';\n`;
if(process.argv.includes('--check')) {
  if(readFileSync('src/core/contact-kernel.generated.ts','utf8').replace(/\r\n/g,'\n')!==source)throw new Error('Stale contact kernel: run npm run build:contact.');
} else writeFileSync('src/core/contact-kernel.generated.ts',source);
